export type TranslationKey = keyof typeof english;
type LanguageContextValue = {
  language: Language;
  setLanguage: (language: Language) => void;
  t: (key: TranslationKey, values?: Record<string, string | number>) => string;
  label: (value: string) => string;
  translateText: (value: string) => string;
};

const LanguageContext = createContext<LanguageContextValue | null>(null);
const LANGUAGE_KEY = 'sakshya.language';

function initialLanguage(): Language {
  try {
    return window.localStorage.getItem(LANGUAGE_KEY) === 'hi' ? 'hi' : 'en';
  } catch {
    return 'en';
  }
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(initialLanguage);
  useEffect(() => {
    document.documentElement.lang = language === 'hi' ? 'hi' : 'en';
  }, [language]);
  const setLanguage = useCallback((nextLanguage: Language) => {
    setLanguageState(nextLanguage);
    try {
      window.localStorage.setItem(LANGUAGE_KEY, nextLanguage);
    } catch {
      // The current view still switches if browser storage is unavailable.
    }
  }, []);
  const t = useCallback((key: TranslationKey, values: Record<string, string | number> = {}) => {
    const dictionary = language === 'hi' ? hindi : english;
    return dictionary[key].replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? `{${name}}`));
  }, [language]);
  const label = useCallback((value: string) => {
    const key = enumTranslations[value];
    if (key) return t(key);
    if (language === 'hi' && roleTranslations[value]) return roleTranslations[value];
    return value.toLowerCase().split('_').map((part) => part.charAt(0).toUpperCase() + part.slice(1)).join(' ');
  }, [language, t]);
  const translateText = useCallback((value: string) => {
    const navKey = navTranslations[value];
    if (navKey) return t(navKey);
    const key = (Object.keys(english) as TranslationKey[]).find((candidate) => english[candidate] === value);
    return key ? t(key) : value;
  }, [t]);
  const context = useMemo(() => ({ language, setLanguage, t, label, translateText }), [language, setLanguage, t, label, translateText]);
  return <LanguageContext.Provider value={context}>{children}</LanguageContext.Provider>;
}

export function useLanguage(): LanguageContextValue {
  const context = useContext(LanguageContext);
  if (!context) throw new Error('useLanguage must be used inside LanguageProvider');
  return context;
}

export function LanguageToggle() {
  const { language, setLanguage, t } = useLanguage();
  return (
    <div className="language-toggle" role="group" aria-label={t('language.label')}>
      <Languages size={15} aria-hidden="true" />
      <button type="button" aria-pressed={language === 'en'} aria-label={t('language.switchToEnglish')} onClick={() => setLanguage('en')}>EN</button>
      <span aria-hidden="true">|</span>
      <button type="button" aria-pressed={language === 'hi'} aria-label={t('language.switchToHindi')} onClick={() => setLanguage('hi')}>हिन्दी</button>
    </div>
  );
}
